"""Record the eval cassette (and, with --write-baseline, ``baseline.json``).

Owner re-record against a real endpoint (a manual step, never run in CI)::

    EVAL_LLM_API_KEY=... python -m review.eval.record --version v1 \\
        --endpoint https://llm.example/v1 --model <model> --write-baseline

``--synthetic`` writes cassettes with no network call: responses are derived
from the corpus labels by a fixed policy and the file says so. Request
headers (``Authorization``, cookies) are forwarded to the endpoint but never
written; only request and response bodies are stored.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import re
from pathlib import Path
from typing import Any

import httpx

from adapter.llm.litellm_client import LiteLLMClient
from review.eval.cassette import (
    Cassette,
    Interaction,
    Produce,
    forward_to_endpoint,
    record,
    save_cassette,
)
from review.eval.corpus import EVAL_DIR, EvalRow, load_corpus
from review.eval.metrics import Metrics, compute_metrics
from review.eval.run import run_eval

REPLAY_ENDPOINT = "https://eval.invalid/v1"
SYNTHETIC_MODEL = "synthetic-eval-model"
CASSETTE_DIR = EVAL_DIR / "cassettes"
BASELINE_PATH = EVAL_DIR / "baseline.json"

_RERECORD = (
    "EVAL_LLM_API_KEY=<key> python -m review.eval.record --version {version} "
    "--endpoint <openai-compatible /v1 url> --model <model> --write-baseline"
)
_SYNTHETIC_V2_NOTE = (
    "SYNTHETIC: no live LLM was called. Responses were generated by "
    "`python -m review.eval.record --version v2 --synthetic` from the corpus labels: "
    "the judge applies the v1 policy and additionally fails not_style_only for the "
    "categories in _STYLE_CATEGORIES; every generated finding carries a placeholder "
    "scenario and a tier derived from severity. Replace with a real recording "
    "before trusting any number derived from it."
)
_SYNTHETIC_NOTE = (
    "SYNTHETIC: no live LLM was called. Responses were generated by "
    "`python -m review.eval.record --synthetic` from the corpus labels (the "
    "baseline judge keeps every true positive and the noise categories in "
    "_SYNTHETIC_V1_NOISE_KEPT). Replace with a real recording before trusting "
    "any number derived from it."
)
# The synthetic v1 judge is deliberately leaky on these noise categories.
_SYNTHETIC_V1_NOISE_KEPT = frozenset({"style", "speculative"})
# The synthetic v2 judge fails the not_style_only criterion on these categories.
_STYLE_CATEGORIES = frozenset({"style", "lint", "complexity"})
_SYNTHETIC_TIER: dict[str, str] = {
    "critical": "blocker",
    "high": "blocker",
    "medium": "should_fix",
    "low": "nit",
    "info": "nit",
}


# A closed set of file names: the CLI value only selects one, it never becomes part of a path.
_CASSETTE_FILES = {"v1": "v1.json", "v2": "v2.json"}


def cassette_path(version: str) -> Path:
    return CASSETTE_DIR / _CASSETTE_FILES[version]


def baseline_dict(metrics: Metrics, *, version: str, synthetic: bool) -> dict[str, Any]:
    return {"version": version, "synthetic": synthetic, "metrics": metrics.model_dump()}


def _completion(content: dict[str, Any], model: str) -> dict[str, Any]:
    return {
        "id": "synthetic",
        "object": "chat.completion",
        "created": 0,
        "model": model,
        "choices": [
            {
                "index": 0,
                "message": {"role": "assistant", "content": json.dumps(content)},
                "finish_reason": "stop",
            }
        ],
        "usage": {"prompt_tokens": 1, "completion_tokens": 1, "total_tokens": 2},
    }


def synthetic_producer(
    rows: list[EvalRow], model: str, *, review_quality_v2: bool = False
) -> Produce:
    by_text = {r.finding_text: r for r in rows}

    async def produce(request: httpx.Request) -> tuple[int, dict[str, Any]]:
        system, user = (m["content"] for m in json.loads(request.content)["messages"])
        if system.startswith("You are an automated code review verification"):
            match = re.search(r'"index"\):\n(\[.*\])\n\nDiff:', user)
            if match is None:
                raise ValueError("synthetic producer could not read the candidate list")
            verdicts = []
            for candidate in json.loads(match.group(1)):
                row = by_text[candidate["message"]]
                keep = row.label == "true_positive" or row.category in _SYNTHETIC_V1_NOISE_KEPT
                verdict = {
                    "index": candidate["index"],
                    "valid": keep,
                    "actionable": keep,
                    "specific": keep,
                    "valuable": keep,
                }
                if review_quality_v2:
                    verdict["not_style_only"] = row.category not in _STYLE_CATEGORIES
                verdicts.append(verdict)
            return 200, _completion({"verdicts": verdicts}, model)
        findings = [
            {
                "file": r.file,
                "line": r.line,
                "severity": r.severity,
                "message": r.finding_text,
                "context_ref_ids": None,
                **(
                    {
                        "scenario": f"Synthetic scenario for {r.id}.",
                        "tier": _SYNTHETIC_TIER[r.severity],
                    }
                    if review_quality_v2
                    else {}
                ),
            }
            for r in rows
            if r.diff_excerpt is not None and r.diff_excerpt in user
        ]
        return 200, _completion({"findings": findings}, model)

    return produce


async def record_version(
    rows: list[EvalRow],
    *,
    version: str,
    produce: Produce,
    endpoint: str,
    api_key: str,
    model: str,
    synthetic: bool,
    review_quality_v2: bool = False,
) -> tuple[Cassette, Metrics]:
    interactions: list[Interaction] = []
    with record(produce, interactions):
        outcomes = await run_eval(
            rows,
            LiteLLMClient(endpoint=endpoint, api_key=api_key),
            model=model,
            review_quality_v2=review_quality_v2,
        )
    synthetic_note = _SYNTHETIC_V2_NOTE if review_quality_v2 else _SYNTHETIC_NOTE
    # The committed baseline is v1's: only a v1 re-record rewrites it.
    rerecord = _RERECORD if not review_quality_v2 else _RERECORD.replace(" --write-baseline", "")
    cassette = Cassette(
        synthetic=synthetic,
        model=model,
        note=synthetic_note if synthetic else f"Recorded against a live endpoint, model {model}.",
        rerecord=rerecord.format(version=version),
        interactions=interactions,
    )
    return cassette, compute_metrics(outcomes)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m review.eval.record", description=__doc__)
    parser.add_argument(
        "--version",
        default="v1",
        choices=sorted(_CASSETTE_FILES),
        help="cassette set name (v1 = baseline prompt; v2 = review_quality_v2 prompt)",
    )
    parser.add_argument("--synthetic", action="store_true", help="no network; derive responses")
    parser.add_argument("--endpoint", help="OpenAI-compatible base URL (real recording)")
    parser.add_argument("--model", help="model name sent to the endpoint (real recording)")
    parser.add_argument("--write-baseline", action="store_true", help="also write baseline.json")
    args = parser.parse_args(argv)

    rows = load_corpus()
    v2 = args.version == "v2"
    if args.synthetic:
        model, endpoint, api_key = SYNTHETIC_MODEL, REPLAY_ENDPOINT, "synthetic-placeholder"
        produce = synthetic_producer(rows, model, review_quality_v2=v2)
    else:
        if not (args.endpoint and args.model and os.environ.get("EVAL_LLM_API_KEY")):
            parser.error("real recording needs --endpoint, --model and EVAL_LLM_API_KEY")
        model, endpoint, api_key = args.model, args.endpoint, os.environ["EVAL_LLM_API_KEY"]
        produce = forward_to_endpoint

    cassette, metrics = asyncio.run(
        record_version(
            rows,
            version=args.version,
            produce=produce,
            endpoint=endpoint,
            api_key=api_key,
            model=model,
            synthetic=args.synthetic,
            review_quality_v2=v2,
        )
    )
    save_cassette(cassette_path(args.version), cassette)
    if args.write_baseline and not v2:
        BASELINE_PATH.write_text(
            json.dumps(
                baseline_dict(metrics, version=args.version, synthetic=args.synthetic),
                indent=2,
                sort_keys=True,
            )
            + "\n"
        )
    print(f"wrote {cassette_path(args.version)} ({len(cassette.interactions)} interactions)")


if __name__ == "__main__":
    main()
